// Writes lib/llama-archs.generated.ts: the `general.architecture` values the
// installed llama.rn's llama.cpp can load. The app checks a GGUF's
// architecture against this list before loading, so a model that needs a
// newer engine gets a clear message instead of a failed native load.
//
// Runs from `npm run setup-native` and `postinstall`. Never fails the
// install: if the source can't be found the committed file is left as is.

const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const pkgDir = path.join(root, 'node_modules', 'llama.rn');
const outFile = path.join(root, 'lib', 'llama-archs.generated.ts');

// llama.rn 0.12 ships the source under cpp/, 0.13 under vendor/llama.cpp/src/.
const candidates = [
  path.join(pkgDir, 'cpp', 'llama-arch.cpp'),
  path.join(pkgDir, 'vendor', 'llama.cpp', 'src', 'llama-arch.cpp'),
];

function main() {
  const source = candidates.find((f) => fs.existsSync(f));
  if (!source) {
    console.warn('[gen-llama-archs] llama-arch.cpp not found, keeping the existing list');
    return;
  }
  const text = fs.readFileSync(source, 'utf8');
  const archs = new Set();
  for (const m of text.matchAll(/\{\s*LLM_ARCH_[A-Z0-9_]+,\s*"([^"]+)"/g)) {
    if (m[1] !== '(unknown)') archs.add(m[1]);
  }
  if (archs.size < 50) {
    console.warn(`[gen-llama-archs] only ${archs.size} architectures parsed, keeping the existing list`);
    return;
  }
  const version = require(path.join(pkgDir, 'package.json')).version;
  const body =
    `// Generated by scripts/gen-llama-archs.js from llama.rn ${version}. Do not edit.\n` +
    `export const LLAMA_RN_VERSION = '${version}';\n\n` +
    `export const LLAMA_CPP_ARCHS: readonly string[] = [\n` +
    [...archs].map((a) => `  '${a}',\n`).join('') +
    `];\n`;
  if (fs.existsSync(outFile) && fs.readFileSync(outFile, 'utf8') === body) return;
  fs.writeFileSync(outFile, body);
  console.log(`[gen-llama-archs] wrote ${archs.size} architectures for llama.rn ${version}`);
}

try {
  main();
} catch (err) {
  console.warn('[gen-llama-archs] skipped:', err && err.message);
}
